# Regression gate for `rake ai:eval`.
#
# The baseline (test/anomaly_eval_baseline.yml) records, per labeled week, the
# last accepted eval outcome: whether the parsed status matched, and for each
# must_flag / must_not_flag item whether it was caught / clean. `rake ai:eval`
# compares a fresh scorecard against it and fails when something that was
# good in the baseline has gone bad.
#
# Comparison is per item, not per week, so a week that already had one known
# miss still fails if a *different* item starts missing.
#
# Noise tolerance: the status is parsed deterministically from the agent's
# report, so a status regression fails immediately. must_flag / must_not_flag
# verdicts come from a Haiku judge that can flip between runs on the same text,
# so a week whose only regressions are findings gets its *saved report*
# re-judged once (the agent is not re-run). Only regressions that survive the
# second judgment fail the run; ones that clear are reported as "flaky".
class AnomalyEvalBaseline
  PATH = Rails.root.join("test/anomaly_eval_baseline.yml")

  WeekDiff = Struct.new(:week_id, :regressions, :improvements, :rejudged, keyword_init: true) do
    def regressed? = regressions.any?
    def improved? = !regressed? && improvements.any?
  end

  Comparison = Struct.new(:regressed, :improved, :unchanged, :flaky, :new_weeks, :not_run, keyword_init: true) do
    def regressed? = regressed.any?
  end

  # Loads a scorecard written by `rake ai:eval` (symbol keys, float costs).
  def self.load_scorecard(path)
    YAML.load_file(path, permitted_classes: [ Symbol, BigDecimal ])
  end

  # Returns the baseline's weeks hash, or nil when no baseline has been recorded.
  def self.load(path = PATH)
    return nil unless File.exist?(path)

    data = YAML.load_file(path) || {}
    weeks = data["weeks"]
    weeks.presence
  end

  # Condense one scorecard row into the stored baseline shape.
  def self.week_entry(row)
    must_flag = Array(row[:must_flag_detail]).to_h { |d| [ d[:item], d[:found] ? "caught" : "missed" ] }
    must_not_flag = Array(row[:must_not_flag_detail]).to_h { |d| [ d[:item], d[:violated] ? "violated" : "clean" ] }
    {
      "expected" => row[:expected],
      "actual" => row[:actual],
      "status_ok" => row[:status_ok],
      "must_flag" => must_flag,
      "must_not_flag" => must_not_flag
    }
  end

  # Merge scorecard rows into an existing baseline. Weeks that errored are
  # skipped (an API failure is not an accepted outcome); weeks missing from
  # `results` keep their previous entry, so a single-week run only refreshes
  # that week. Weeks no longer in `expectations` are dropped.
  def self.merge(existing, results, expectations:)
    weeks = (existing || {}).slice(*expectations.keys)
    skipped = []
    results.each do |row|
      if row[:actual] == "ERROR"
        skipped << row[:week_id]
        next
      end
      weeks[row[:week_id]] = week_entry(row)
    end
    [ weeks.sort.to_h, skipped ]
  end

  def self.write(weeks, meta:, path: PATH)
    header = <<~YAML
      # Accepted `rake ai:eval` outcomes, used as the regression gate.
      # Generated by `rake ai:eval_baseline` from the latest tmp/ai_eval scorecard.
      # Do not hand-edit; re-run the eval and refresh instead. See CLAUDE.md.
    YAML
    File.write(path, header + { "meta" => meta, "weeks" => weeks }.to_yaml)
  end

  def initialize(baseline_weeks)
    @baseline = baseline_weeks || {}
  end

  # `rejudge` is called with a scorecard row whose only regressions are judge
  # findings and must return a replacement row (same shape) from a second
  # judgment of the same report. Pass nil to disable re-judging.
  def compare(results, rejudge: nil)
    comparison = Comparison.new(regressed: [], improved: [], unchanged: [], flaky: [], new_weeks: [], not_run: [])
    seen = []

    results.sort_by { |r| r[:week_id] }.each do |row|
      week_id = row[:week_id]
      seen << week_id
      base = @baseline[week_id]
      unless base
        comparison.new_weeks << week_id
        next
      end

      diff = diff_week(base, row)
      if diff.regressed? && rejudge && judge_only?(diff)
        rejudged_row = rejudge.call(row)
        second = diff_week(base, rejudged_row)
        if second.regressed?
          diff = second
          diff.rejudged = true
        else
          comparison.flaky << diff
          diff = second
        end
      end

      if diff.regressed?
        comparison.regressed << diff
      elsif diff.improved?
        comparison.improved << diff
      else
        comparison.unchanged << week_id
      end
    end

    comparison.not_run = (@baseline.keys - seen).sort
    comparison
  end

  def self.format(comparison)
    lines = [ "", "=" * 72, "BASELINE COMPARISON", "=" * 72 ]
    comparison.regressed.each do |d|
      lines << "  REGRESSED  #{d.week_id}#{' (still failing after re-judge)' if d.rejudged}"
      d.regressions.each { |r| lines << "             - #{r}" }
    end
    comparison.improved.each do |d|
      lines << "  IMPROVED   #{d.week_id}"
      d.improvements.each { |r| lines << "             + #{r}" }
    end
    comparison.flaky.each do |d|
      lines << "  FLAKY      #{d.week_id} (judge regression cleared on re-judge)"
      d.regressions.each { |r| lines << "             ~ #{r}" }
    end
    lines << "  NEW        #{comparison.new_weeks.join(', ')} (not in baseline)" if comparison.new_weeks.any?
    lines << "-" * 72
    lines << "  Regressed: #{comparison.regressed.size}  Improved: #{comparison.improved.size}  " \
             "Unchanged: #{comparison.unchanged.size}  Flaky: #{comparison.flaky.size}  " \
             "New: #{comparison.new_weeks.size}  Not run: #{comparison.not_run.size}"
    lines << "=" * 72
    lines.join("\n")
  end

  private

  STATUS_PREFIX = "status:".freeze

  def judge_only?(diff)
    diff.regressions.none? { |r| r.start_with?(STATUS_PREFIX) }
  end

  def diff_week(base, row)
    current = self.class.week_entry(row)
    regressions = []
    improvements = []

    if base["status_ok"] && !current["status_ok"]
      regressions << "#{STATUS_PREFIX} expected #{current['expected']}, got #{current['actual']} (baseline got #{base['actual']})"
    elsif !base["status_ok"] && current["status_ok"]
      improvements << "#{STATUS_PREFIX} now #{current['actual']} as expected (baseline got #{base['actual']})"
    end

    # An errored row has no finding details; the status regression above covers it.
    unless row[:actual] == "ERROR"
      compare_items(base["must_flag"], current["must_flag"], good: "caught", label: "must_flag",
                    regressions: regressions, improvements: improvements)
      compare_items(base["must_not_flag"], current["must_not_flag"], good: "clean", label: "must_not_flag",
                    regressions: regressions, improvements: improvements)
    end

    WeekDiff.new(week_id: row[:week_id], regressions: regressions, improvements: improvements, rejudged: false)
  end

  # Items added to the expectations since the baseline was recorded have no
  # prior outcome, so they can't regress.
  def compare_items(base_items, current_items, good:, label:, regressions:, improvements:)
    (base_items || {}).each do |item, base_outcome|
      outcome = current_items[item]
      next if outcome.nil? || outcome == base_outcome

      if base_outcome == good
        regressions << "#{label} now #{outcome}: #{item}"
      else
        improvements << "#{label} now #{outcome}: #{item}"
      end
    end
  end
end
